import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

export const migrationFiles = [
  "202610040001_private_groups.sql",
  "202610040002_collaboration.sql",
  "202610040003_profiles_group_names.sql",
];
export async function buildInstallSql() {
  const bodies = [];
  for (const name of migrationFiles) {
    const text = (
      await readFile(
        new URL(`../supabase/migrations/${name}`, import.meta.url),
        "utf8",
      )
    ).replaceAll("\r\n", "\n");
    if (
      (text.match(/^begin;\s*$/gim) ?? []).length !== 1 ||
      (text.match(/^commit;\s*$/gim) ?? []).length !== 1
    )
      throw new Error(`Expected one top-level transaction in ${name}`);
    bodies.push(
      `-- Source: ${name}\n${text
        .replace(/^begin;\s*$/im, "")
        .replace(/^commit;\s*$/im, "")
        .trim()}\n`,
    );
  }
  const tables = bodies.flatMap((body) =>
    [...body.matchAll(/create table public\.(\w+)/gi)].map((match) => match[1]),
  );
  const list = tables.map((table) => `'${table}'`).join(", ");
  return `-- Group Trip Planner: first installation only.\n-- Generated by node scripts/build-install-sql.mjs; do not edit this copy.\n-- Run this WHOLE file ONCE in the correct Supabase SQL Editor.\n-- Contains migrations ${migrationFiles.join(", ")}.\n-- No private trip data is included. Existing app installations must use migrations instead.\nbegin;\ndo $$\nbegin\n  if exists (select 1 from pg_catalog.pg_namespace where nspname = 'app_private')\n     or exists (select 1 from pg_catalog.pg_tables where schemaname = 'public' and tablename in (${list})) then\n    raise exception 'Existing Group Trip Planner schema detected. Stop and inspect before applying migrations. No changes applied.';\n  end if;\nend $$;\n\n${bodies.join("\n")}\ncommit;\n`;
}

const direct =
  process.argv[1] &&
  fileURLToPath(import.meta.url) === resolve(process.argv[1]);
if (direct) {
  const output = new URL("../supabase/INSTALL_ALL.sql", import.meta.url);
  const generated = await buildInstallSql();
  if (process.argv.includes("--check")) {
    if ((await readFile(output, "utf8")).replaceAll("\r\n", "\n") !== generated)
      throw new Error(
        "INSTALL_ALL.sql is stale. Run node scripts/build-install-sql.mjs.",
      );
    console.log("INSTALL_ALL.sql matches all migrations.");
  } else {
    await writeFile(output, generated, "utf8");
    console.log(
      "Generated supabase/INSTALL_ALL.sql (single transaction, fresh schema only).",
    );
  }
}
